        /// <summary>
        /// Tên tiếng Việt của một mã. Rỗng → "chưa xác định"; chữ không phải mã (dữ liệu cũ đã là
        /// tiếng Việt) giữ nguyên; mã lạ → "trạng thái khác" (KHÔNG trả lại mã).
        /// </summary>
        public static string Of(string? code)
        {
            var value = code?.Trim();
            if (string.IsNullOrEmpty(value)) return "chưa xác định";
            var key = value.ToUpperInvariant().Replace(' ', '_').Replace('-', '_');
            if (Labels.TryGetValue(key, out var label)) return label;
            return !IsReadable(value) && CodeLike.IsMatch(key) ? "trạng thái khác" : value;
        }

        /// <summary>Tên trong ngoặc kép để chèn giữa câu: “Đã huỷ”.</summary>
        public static string Quote(string? code) => $"“{Of(code)}”";

        /// <summary>Nhiều mã → "“A”, “B” hoặc “C”".</summary>
        public static string QuoteAny(params string[] codes)
        {
            if (codes == null || codes.Length == 0) return string.Empty;
            var names = Array.ConvertAll(codes, Quote);
            return names.Length == 1
                ? names[0]
                : string.Join(", ", names, 0, names.Length - 1) + " hoặc " + names[^1];
        }

        /* Có dấu tiếng Việt hoặc có khoảng trắng → là chữ người đọc, không phải mã. */
        private static bool IsReadable(string value)
        {
            foreach (var c in value)
            {
                if (c > 127 || char.IsWhiteSpace(c)) return true;
            }
            return false;
        }
